# ── Label grammar ────────────────────────────────────────────────────────────

LEADER_LABEL_RE = re.compile(r"^(Area |Floor |)Leader: (.+)$")
PROVIDES_LABEL_RE = re.compile(r"^(Area |Floor |)Provides: (.+)$")
MODE_LABEL_RE = re.compile(r"^(Area |Floor |)(.+) Mode: (Leader|Any|All)$")
# Modifier labels must not register as features in the label_map. Mirrors the
# legacy regex: ^[^:]+ (Component|Min|Max|Step|Unit|Icon|Initial|Static|Mode|Device Class): _
_PROVIDES_MODIFIER_RE = re.compile(
    r"^[^:]+ (" + "|".join(PROVIDES_MODIFIER_KEYWORDS) + r"): "
)

SCOPE_PREFIXES = {SCOPE_AREA: "Area ", SCOPE_FLOOR: "Floor ", SCOPE_GLOBAL: ""}


def scope_prefix(scope: str) -> str:
    """Return the label prefix for a scope ('Area ' / 'Floor ' / '')."""
    return SCOPE_PREFIXES.get(scope, "")


def _value_after_last_colon(label: str) -> str:
    """Replicate the legacy `regex_replace('^.+: ', '')` greedy behavior.

    The legacy pattern `.+: ` is greedy, so it consumes up to the LAST ': '
    in the label. For ordinary labels this is the value after the single
    colon; for values containing ': ' it keeps only the trailing segment.
    """
    return label.rsplit(": ", 1)[-1].strip()


def _is_skip_value(value: str) -> bool:
    """Skip-values: *_initial_press, unknown/unavailable/none."""
    return value.endswith(SKIP_SUFFIX) or value.lower() in SKIP_STATES


def _to_float(value: Any) -> float | None:
    """Best-effort float conversion (None when not numeric)."""
    try:
        return float(value)
    except (TypeError, ValueError):
        return None


def as_bool(value: Any, default: bool = False) -> bool:
    """Replicate HA's `| bool(default)` Jinja filter.

    Strings go through strtobool semantics ('true/on/yes/1' vs
    'false/off/no/0'); unrecognized values fall back to the default. This
    matters because the legacy labeled_feature_set event carries the enabled
    flag as a rendered string ('True' / 'False').
    """
    if isinstance(value, bool):
        return value
    if isinstance(value, (int, float)):
        return value != 0
    if isinstance(value, str):
        lowered = value.strip().lower()
        if lowered in ("true", "on", "yes", "1", "enable", "enabled"):
            return True
        if lowered in ("false", "off", "no", "0", "disable", "disabled"):
            return False
    return default


# ── Leader definitions ───────────────────────────────────────────────────────


@dataclass(frozen=True)
class LeaderDef:
    """A resolved (entity, feature, scope) leader definition.

    Combines the triple location with the modifier configuration used by
    eval_leader. `source` records whether the definition came from labels or
    from a config subentry (subentries win on conflict).
    """

    entity_id: str
    feature: str
    scope: str  # area | floor | global
    scope_id: str  # area_id / floor_id / '' for global
    source: str  # 'label' | 'subentry'
    increasing: bool = False
    decreasing: bool = False
    enable: str | None = None
    disable: str | None = None
    invert: bool = False

    @property
    def triple_key(self) -> str:
        """The (feature, scope, scope_id) triple key."""
        return f"{self.feature}||{self.scope}||{self.scope_id}"


@dataclass
class EngineError:
    """A routable error produced by the engine."""

    key: str
    message: str
    context: dict[str, Any] = field(default_factory=dict)


def extract_label_modifiers(
    label_names: list[str], feature: str, scope: str
) -> dict[str, Any]:
    """Extract eval modifiers for (feature, scope) from an entity's labels.

    Mirrors the legacy label shapes (all case-sensitive):
      <pfx><F> Increasing: True   <pfx><F> Decreasing: True
      <pfx><F> Enable: <v>        <pfx><F> Disable: <v>
      <pfx><F> Invert: True
    """
    pfx = scope_prefix(scope)
    head = f"{pfx}{feature}"
    enable: str | None = None
    disable: str | None = None
    for lbl in label_names:
        if lbl.startswith(f"{head} Enable: ") and len(lbl) > len(f"{head} Enable: "):
            if enable is None:  # legacy takes the FIRST match
                enable = _value_after_last_colon(lbl)
        elif lbl.startswith(f"{head} Disable: ") and len(lbl) > len(
            f"{head} Disable: "
        ):
            if disable is None:
                disable = _value_after_last_colon(lbl)
    return {
        "increasing": f"{head} Increasing: True" in label_names,
        "decreasing": f"{head} Decreasing: True" in label_names,
        "enable": enable,
        "disable": disable,
        "invert": f"{head} Invert: True" in label_names,
    }


def subentry_modifiers(data: Mapping[str, Any]) -> dict[str, Any]:
    """Normalize a leader subentry's data into eval modifiers."""
    direction = data.get(SUBCONF_DIRECTION, DIRECTION_NONE)
    enable = (data.get(SUBCONF_ENABLE_VALUE) or "").strip()
    disable = (data.get(SUBCONF_DISABLE_VALUE) or "").strip()
    return {
        "increasing": direction in (DIRECTION_INCREASING, DIRECTION_BOTH),
        "decreasing": direction in (DIRECTION_DECREASING, DIRECTION_BOTH),
        "enable": enable or None,
        "disable": disable or None,
        "invert": bool(data.get(SUBCONF_INVERT, False)),
    }


def eval_leader(
    *,
    feature: str,
    domain: str,
    state: str,
    current: str,
    previous: str,
    increasing: bool,
    decreasing: bool,
    enable: str | None,
    disable: str | None,
    invert: bool,
) -> bool:
    """Evaluate one leader's truth for one feature (post-Invert).

    Parity with the legacy eval_leader macro:
      1. Direction labels take precedence (numeric current vs previous;
         non-numeric / first update -> False; Increasing and Decreasing OR'd).
      2. Else Enable/Disable state-equality values.
      3. Else default truth: state == feature (case-sensitive) OR state in the
         truthy set (case-insensitive); event/button domains are always True.
      4. Invert applies last.

    `state` is the raw current state string (used by Enable/Disable/default).
    `current`/`previous` feed Direction (for event-domain leaders `current`
    carries the event_type, matching the legacy leaders-attribute semantics).
    """
    if increasing or decreasing:
        cur_n = _to_float(current)
        prev_n = _to_float(previous)
        has_mov = cur_n is not None and prev_n is not None
        is_inc = has_mov and cur_n > prev_n  # type: ignore[operator]
        is_dec = has_mov and cur_n < prev_n  # type: ignore[operator]
        base = (increasing and is_inc) or (decreasing and is_dec)
    elif enable is not None or disable is not None:
        by_en = enable is not None and state == enable
        by_dis = disable is not None and state == disable
        if enable is not None and disable is not None:
            base = by_en and not by_dis
        elif enable is not None:
            base = by_en
        else:
            base = not by_dis
    elif domain in MOMENTARY_DOMAINS:
        base = True
    else:
        base = state == feature or state.lower() in TRUTHY_STATES
    return (not base) if invert else base


def build_leader_defs(
    *,
    labeled_leaders: Mapping[str, list[str]],
    leader_subentries: list[Mapping[str, Any]],
    entity_ctx: Mapping[str, Mapping[str, str]],
) -> tuple[dict[tuple[str, str, str], LeaderDef], list[EngineError]]:
    """Build resolved leader definitions from labels + subentries.

    `labeled_leaders` maps entity_id -> label names for every leader entity
    (the `feature_leader` label set UNION the subentry-referenced entities).
    `entity_ctx` maps entity_id -> {'area_id': ..., 'floor_id': ...}.

    Returns (defs, errors) where defs is keyed by (entity_id, feature, scope).
    Subentry definitions win over a label definition for the same key.
    Leaders whose scope cannot be resolved are skipped with an error.
    """
    defs: dict[tuple[str, str, str], LeaderDef] = {}
    errors: list[EngineError] = []

    def _resolve_scope(
        eid: str, feature: str, scope: str, source: str
    ) -> str | None:
        ctx = entity_ctx.get(eid, {})
        area_id = ctx.get("area_id", "")
        floor_id = ctx.get("floor_id", "")
        if scope == SCOPE_AREA:
            if area_id == "":
                errors.append(
                    EngineError(
                        ISSUE_LEADER_NO_AREA,
                        f"Leader '{eid}' leads '{feature}' at area scope but has no area.",
                        {"entity_id": eid, "feature": feature, "source": source},
                    )
                )
                return None
            return area_id
        if scope == SCOPE_FLOOR:
            if floor_id == "":
                errors.append(
                    EngineError(
                        ISSUE_LEADER_NO_FLOOR,
                        f"Leader '{eid}' leads '{feature}' at floor scope but its area has no floor.",
                        {"entity_id": eid, "feature": feature, "source": source},
                    )
                )
                return None
            return floor_id
        return ""  # global

    # Pass 1 — label definitions.
    for eid, label_names in labeled_leaders.items():
        for lbl in label_names:
            if not (m := LEADER_LABEL_RE.match(lbl)):
                continue
            prefix, feature = m.group(1).strip(), m.group(2).strip()
            scope = (
                SCOPE_AREA
                if prefix == "Area"
                else SCOPE_FLOOR
                if prefix == "Floor"
                else SCOPE_GLOBAL
            )
            if (scope_id := _resolve_scope(eid, feature, scope, "label")) is None:
                continue
            mods = extract_label_modifiers(label_names, feature, scope)
            defs[(eid, feature, scope)] = LeaderDef(
                entity_id=eid,
                feature=feature,
                scope=scope,
                scope_id=scope_id,
                source="label",
                **mods,
            )

    # Pass 2 — subentry definitions (win on conflict).
    for data in leader_subentries:
        eid = str(data.get(SUBCONF_ENTITY_ID, "") or "").strip()
        feature = str(data.get(SUBCONF_FEATURE, "") or "").strip()
        scope = str(data.get(SUBCONF_SCOPE, "") or "").strip()
        if eid == "" or feature == "" or scope not in SCOPE_PREFIXES:
            continue
        if (scope_id := _resolve_scope(eid, feature, scope, "subentry")) is None:
            continue
        mods = subentry_modifiers(data)
        defs[(eid, feature, scope)] = LeaderDef(
            entity_id=eid,
            feature=feature,
            scope=scope,
            scope_id=scope_id,
            source="subentry",
            **mods,
        )

    return defs, errors


def build_triples(
    defs: Mapping[tuple[str, str, str], LeaderDef],
) -> dict[str, list[str]]:
    """Map triple keys ('feature||scope||scope_id') to leader entity_ids."""
    triples: dict[str, list[str]] = {}
    for leader_def in defs.values():
        leaders = triples.setdefault(leader_def.triple_key, [])
        if leader_def.entity_id not in leaders:
            leaders.append(leader_def.entity_id)
    return triples


def resolve_modes(
    *,
    triple_keys: list[str],
    mode_subentries: list[Mapping[str, Any]],
    sensor_label_names: list[str],
) -> dict[str, str]:
    """Resolve the fold mode per triple.

    Priority: Mode subentry for (feature, scope) -> '<Scoped F> Mode:' label
    on the instance's sensor entity -> 'leader'.
    """
    sub_modes: dict[tuple[str, str], str] = {}
    for data in mode_subentries:
        feature = str(data.get(SUBCONF_FEATURE, "") or "").strip()
        scope = str(data.get(SUBCONF_SCOPE, "") or "").strip()
        mode = str(data.get(SUBCONF_MODE, "") or "").strip().lower()
        if feature and scope and mode in FOLD_MODES:
            sub_modes[(feature, scope)] = mode

    modes: dict[str, str] = {}
    for key in triple_keys:
        parts = key.split("||")
        feature, scope = parts[0], parts[1]
        if (mode := sub_modes.get((feature, scope))) is not None:
            modes[key] = mode
            continue
        # Label lookup (case-sensitive, full-string match, value lowercased).
        found = "leader"
        pfx = scope_prefix(scope)
        for lbl in sensor_label_names:
            if m := MODE_LABEL_RE.match(lbl):
                if m.group(2) == feature and (m.group(1).strip() == pfx.strip()):
                    found = m.group(3).lower()
                    break
        modes[key] = found
    return modes


