def update_leaders(
    *,
    prev: Mapping[str, Any],
    all_leader_ids: list[str],
    changed_eid: str | None,
    cv_raw: str | None,
    changed_ts: float | None,
    seed_fn: Callable[[str], tuple[str, float]],
) -> dict[str, dict[str, Any]]:
    """Update the leaders attribute (legacy lines 323-373).

    Carry non-orphans through, seed newly-labeled leaders, and rebuild the
    changed leader's entry (skip-values carry the previous entry through).
    `seed_fn(entity_id) -> (current_state, last_changed_timestamp)` is used
    for newly-seen leaders only.
    """
    prev_map = prev if isinstance(prev, Mapping) else {}
    result: dict[str, dict[str, Any]] = {}

    for eid, ldat in prev_map.items():
        if eid in all_leader_ids and eid != changed_eid:
            result[eid] = dict(ldat) if isinstance(ldat, Mapping) else {}

    for eid in all_leader_ids:
        if eid not in result and eid != changed_eid:
            state, ts = seed_fn(eid)
            result[eid] = {
                "current_value": state,
                "previous_value": "",
                "last_changed_timestamp": ts,
            }

    if changed_eid is not None and changed_eid in all_leader_ids:
        value = cv_raw if cv_raw is not None else ""
        ts = changed_ts if changed_ts is not None else 0.0
        is_skip = _is_skip_value(value)
        prev_l = prev_map.get(changed_eid, {})
        prev_l = prev_l if isinstance(prev_l, Mapping) else {}
        if is_skip:
            cv = prev_l.get("current_value", value)
            cv_ts = prev_l.get("last_changed_timestamp", ts)
        else:
            cv = value
            cv_ts = ts
        old_cv = prev_l.get("current_value", "")
        old_pv = prev_l.get("previous_value", "")
        prev_cv_raw = old_cv if cv != old_cv else old_pv
        prev_cv = "" if _is_skip_value(str(prev_cv_raw)) else prev_cv_raw
        result[changed_eid] = {
            "current_value": cv,
            "previous_value": prev_cv,
            "last_changed_timestamp": cv_ts,
        }

    return result


def update_features(
    *,
    prev_features: Mapping[str, Any],
    prev_leaders: Mapping[str, Any],
    defs: Mapping[tuple[str, str, str], LeaderDef],
    triples: Mapping[str, list[str]],
    modes: Mapping[str, str],
    get_state: Callable[[str], str],
    changed_eid: str | None = None,
    cv_raw: str | None = None,
    new_state_str: str | None = None,
    changed_ts: float | None = None,
    manual: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Update the features attribute (legacy lines 410-653).

    Carry phase: keep every previous triple that is still leader-mapped or is
    a manual override (triggering_leader == ''); drop the rest.
    Manual phase: write the override entry when `manual` is provided.
    State phase: re-evaluate every triple the changed leader contributes to.
    """
    prev_map = prev_features if isinstance(prev_features, Mapping) else {}
    prev_leaders_map = prev_leaders if isinstance(prev_leaders, Mapping) else {}
    result: dict[str, Any] = {}

    # ── Carry phase ─────────────────────────────────────────────────────────
    for fname, scopes_map in prev_map.items():
        if not isinstance(scopes_map, Mapping):
            continue
        for scope_val, sids in scopes_map.items():
            if not isinstance(sids, Mapping):
                continue
            for scope_id_val, entry in sids.items():
                entry = entry if isinstance(entry, Mapping) else {}
                key = f"{fname}||{scope_val}||{scope_id_val}"
                has_leader = key in triples
                is_manual = entry.get("triggering_leader", "") == ""
                if has_leader or is_manual:
                    result.setdefault(fname, {}).setdefault(scope_val, {})[
                        scope_id_val
                    ] = dict(entry)

    # ── Manual override phase (labeled_feature_set event / set_feature action)
    if manual is not None:
        tgt = str(manual.get("target_feature", "") or "").strip()
        scp = str(manual.get("scope", "") or "").strip().lower()
        sid = str(manual.get("scope_id", "") or "")
        ena = as_bool(manual.get("enabled", False))
        ts = float(manual.get("timestamp", 0.0) or 0.0)
        if tgt != "" and scp in (SCOPE_AREA, SCOPE_FLOOR, SCOPE_GLOBAL):
            prev_entry = (
                result.get(tgt, {}).get(scp, {}).get(sid, {})
                if isinstance(result.get(tgt, {}).get(scp, {}), Mapping)
                else {}
            )
            mode = prev_entry.get("mode", MODE_LEADER)
            result.setdefault(tgt, {}).setdefault(scp, {})[sid] = {
                "enabled": ena,
                "mode": mode,
                "last_changed_timestamp": ts,
                "triggering_leader": "",
            }

    # ── State phase (leader-driven tick) ────────────────────────────────────
    if changed_eid is not None:
        value = cv_raw if cv_raw is not None else ""
        if not _is_skip_value(value):
            ts = changed_ts if changed_ts is not None else 0.0
            prev_l = prev_leaders_map.get(changed_eid, {})
            prev_l = prev_l if isinstance(prev_l, Mapping) else {}
            prev_cv = str(prev_l.get("current_value", ""))
            # Legacy compares Enable/Disable/default-truth against states(eid)
            # at render time ('unknown' for a removed entity).
            state_str = (
                new_state_str
                if new_state_str is not None
                else get_state(changed_eid)
            )
            changed_domain = changed_eid.split(".")[0]

            for key, leaders_list in triples.items():
                if changed_eid not in leaders_list:
                    continue
                parts = key.split("||")
                fname, scope_val, scope_id_val = parts[0], parts[1], parts[2]
                mode = modes.get(key, MODE_LEADER)
                leader_def = defs.get((changed_eid, fname, scope_val))
                if leader_def is None:
                    continue
                this_truth = eval_leader(
                    feature=fname,
                    domain=changed_domain,
                    state=state_str,
                    current=value,
                    previous=prev_cv,
                    increasing=leader_def.increasing,
                    decreasing=leader_def.decreasing,
                    enable=leader_def.enable,
                    disable=leader_def.disable,
                    invert=leader_def.invert,
                )
                if mode == MODE_LEADER:
                    new_enabled = this_truth
                else:
                    values: list[bool] = []
                    for other_eid in leaders_list:
                        if other_eid == changed_eid:
                            values.append(this_truth)
                            continue
                        other_def = defs.get((other_eid, fname, scope_val))
                        if other_def is None:
                            continue
                        other_l = prev_leaders_map.get(other_eid, {})
                        other_l = other_l if isinstance(other_l, Mapping) else {}
                        other_prev = str(other_l.get("previous_value", ""))
                        other_state = get_state(other_eid)
                        values.append(
                            eval_leader(
                                feature=fname,
                                domain=other_eid.split(".")[0],
                                state=other_state,
                                current=other_state,
                                previous=other_prev,
                                increasing=other_def.increasing,
                                decreasing=other_def.decreasing,
                                enable=other_def.enable,
                                disable=other_def.disable,
                                invert=other_def.invert,
                            )
                        )
                    new_enabled = min(values) if mode == MODE_ALL else max(values)

                prev_entry = (
                    result.get(fname, {}).get(scope_val, {}).get(scope_id_val, {})
                )
                prev_entry = prev_entry if isinstance(prev_entry, Mapping) else {}
                prev_enabled = prev_entry.get("enabled")
                prev_ts = prev_entry.get("last_changed_timestamp", ts)
                flipped = (
                    prev_enabled is None
                    or prev_enabled != new_enabled
                    or changed_domain in MOMENTARY_DOMAINS
                )
                new_ts = ts if flipped else prev_ts
                result.setdefault(fname, {}).setdefault(scope_val, {})[
                    scope_id_val
                ] = {
                    "enabled": new_enabled,
                    "mode": mode,
                    "last_changed_timestamp": new_ts,
                    "triggering_leader": changed_eid,
                }

    return result


def update_snapshots(
    *,
    prev: Mapping[str, Any],
    snapshot_name: str | None,
    payload: Any,
) -> dict[str, Any]:
    """Update the snapshots attribute (legacy lines 668-693).

    Non-snapshot ticks (snapshot_name None) carry the dict through unchanged.
    An empty name, or an empty/non-mapping payload, removes the entry.
    """
    prev_map = prev if isinstance(prev, Mapping) else {}
    if snapshot_name is None:
        return dict(prev_map)
    name = snapshot_name.strip()
    if name == "":
        return dict(prev_map)
    out = {k: v for k, v in prev_map.items() if k != name}
    if isinstance(payload, Mapping) and len(payload) > 0:
        out[name] = dict(payload)
    return out


# ── Areas label_map ──────────────────────────────────────────────────────────


def build_label_map(
    *,
    gated_areas: list[Mapping[str, Any]],
    provides_subentries: list[Mapping[str, Any]],
) -> tuple[dict[str, Any], list[EngineError]]:
    """Build the label_map attribute (legacy lines 90-187).

    `gated_areas` items: {'area_id', 'floor_id', 'labels': [label names]}.
    `provides_subentries` items: subentry data dicts, each augmented by the
    coordinator with the declaring area's floor under key '_floor_id'.

    Returns (label_map, errors). Subentry declarations win over label-derived
    entries for the same (scope_id, label).
    """
    errors: list[EngineError] = []
    # scope_id -> {'labels': {label_name: entry}}
    scopes: dict[str, dict[str, Any]] = {}

    def _add_entry(scope_id: str, lname: str, lentry: dict[str, Any], overwrite: bool) -> None:
        bucket = scopes.setdefault(scope_id, {"labels": {}})
        if overwrite or lname not in bucket["labels"]:
            bucket["labels"][lname] = lentry

    # Pass 1 — label declarations on gated areas.
    for area in gated_areas:
        aid = str(area.get("area_id", ""))
        floor_id = str(area.get("floor_id", "") or "")
        area_labels = [l for l in area.get("labels", []) if isinstance(l, str)]
        for lbl in area_labels:
            if not (m := PROVIDES_LABEL_RE.match(lbl)):
                continue
            prefix, lname = m.group(1).strip(), m.group(2).strip()
            if lname == "" or _PROVIDES_MODIFIER_RE.search(lname):
                continue
            scope_val = (
                SCOPE_AREA
                if prefix == "Area"
                else SCOPE_FLOOR
                if prefix == "Floor"
                else SCOPE_NONE
            )
            scope_id_val = aid if scope_val in (SCOPE_AREA, SCOPE_NONE) else floor_id
            if scope_id_val == "":
                errors.append(
                    EngineError(
                        ISSUE_PROVIDES_NO_FLOOR,
                        f"Area '{aid}' declares 'Floor Provides: {lname}' but has no floor.",
                        {"area_id": aid, "label": lname, "source": "label"},
                    )
                )
                continue
            comp_prefix = (
                "Area "
                if scope_val == SCOPE_AREA
                else "Floor "
                if scope_val == SCOPE_FLOOR
                else ""
            )
            comp_override = ""
            comp_head = f"{comp_prefix}Provides {lname} Component: "
            for other in area_labels:
                if other.startswith(comp_head) and len(other) > len(comp_head):
                    comp_override = _value_after_last_colon(other)
                    break
            component = comp_override if comp_override != "" else "select"
            _add_entry(
                scope_id_val,
                lname,
                {
                    "scope": scope_val,
                    "scope_id": scope_id_val,
                    "component": component,
                    "declaring_area_id": aid,
                },
                overwrite=False,
            )

    # Pass 2 — subentry declarations (win on conflict).
    for data in provides_subentries:
        aid = str(data.get(SUBCONF_AREA_ID, "") or "").strip()
        lname = str(data.get(SUBCONF_FEATURE, "") or "").strip()
        scope_val = str(data.get(SUBCONF_SCOPE, "") or "").strip()
        component = str(data.get(SUBCONF_COMPONENT, "") or "select").strip() or "select"
        if aid == "" or lname == "" or scope_val not in (
            SCOPE_AREA,
            SCOPE_FLOOR,
            SCOPE_NONE,
        ):
            continue
        floor_id = str(data.get("_floor_id", "") or "")
        scope_id_val = aid if scope_val in (SCOPE_AREA, SCOPE_NONE) else floor_id
        if scope_id_val == "":
            errors.append(
                EngineError(
                    ISSUE_PROVIDES_NO_FLOOR,
                    f"Provides subentry for area '{aid}' declares floor-scoped '{lname}' but the area has no floor.",
                    {"area_id": aid, "label": lname, "source": "subentry"},
                )
            )
            continue
        _add_entry(
            scope_id_val,
            lname,
            {
                "scope": scope_val,
                "scope_id": scope_id_val,
                "component": component,
                "declaring_area_id": aid,
            },
            overwrite=True,
        )

    # Flatten into the public <scope_id>||<label> map (exact legacy shape).
    label_map: dict[str, Any] = {}
    for sid, sdat in scopes.items():
        for lname, ldat in sdat["labels"].items():
            label_map[f"{sid}||{lname}"] = {
                "scope_id": sid,
                "label": lname,
                "scope": ldat["scope"],
                "component": ldat["component"],
                "declaring_area_id": ldat["declaring_area_id"],
                "label_data": {
                    "scope": ldat["scope"],
                    "scope_id": ldat["scope_id"],
                    "component": ldat["component"],
                    "declaring_area_id": ldat["declaring_area_id"],
                },
            }
    return label_map, errors
