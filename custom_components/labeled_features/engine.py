"""Pure evaluation engine for the Labeled Features integration.

This module is a 1:1 Python port of the Jinja logic that lived in the two
legacy trigger-based template sensors (configuration.yaml). It is deliberately
hass-free: every function takes plain data structures and callbacks so the
behavior is reviewable and testable in isolation.

Parity reference:
  - sensor.labeled_features_state   (configuration.yaml lines 214-693)
  - sensor.labeled_feature_areas_state (configuration.yaml lines 67-187)
  - docs: CuratedForest.com/content/tech/home-assistant/label-based-features/

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

