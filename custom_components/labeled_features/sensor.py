def _entry_option(entry: ConfigEntry, key: str, default: Any) -> Any:
    merged = {**(entry.data or {}), **(entry.options or {})}
    return merged.get(key, default)


async def async_setup_entry(
    hass: HomeAssistant,
    entry: ConfigEntry,
    async_add_entities: AddEntitiesCallback,
) -> None:
    """Create the two Labeled Features sensors for this config entry."""
    features_entity_id = _entry_option(entry, CONF_FEATURES_ENTITY_ID, DEFAULT_FEATURES_ENTITY_ID)
    areas_entity_id = _entry_option(entry, CONF_AREAS_ENTITY_ID, DEFAULT_AREAS_ENTITY_ID)
    instance_name = _entry_option(entry, CONF_INSTANCE_NAME, DEFAULT_INSTANCE_NAME)

    features_sensor = LabeledFeaturesStateSensor(entry, features_entity_id, instance_name)
    areas_sensor = LabeledFeatureAreasStateSensor(entry, areas_entity_id, instance_name)

    async_add_entities([features_sensor, areas_sensor])


