def _resolve_label_id(hass: HomeAssistant, label_name_or_id: str) -> str | None:
    """Return the label_id matching either the label's id or its display name.

    HA's built-in template functions `label_entities()` / `label_areas()`
    accept either form; users may enter the slug (`feature_leader`) or the
    display name (`Feature Leader`). We follow the same convention.
    """
    if not label_name_or_id:
        return None
    label_reg = lr.async_get(hass)
    # Fast path: direct label_id lookup.
    direct = label_reg.async_get_label(label_name_or_id)
    if direct is not None:
        return direct.label_id
    # Fallback: match by display name.
    for lbl in label_reg.async_list_labels():
        if lbl.name == label_name_or_id:
            return lbl.label_id
    return None


def _labels_of(hass: HomeAssistant, *, entity_id: str | None = None,
                area_id: str | None = None) -> list[str]:
    """Return the list of label names attached to an entity or area.

    Returns display names because label parsers match against the
    documented case-sensitive label names (`Area Leader: Screen`, etc).
    """
    label_reg = lr.async_get(hass)
    if entity_id is not None:
        ent_reg = er.async_get(hass)
        ent = ent_reg.async_get(entity_id)
        if ent is None:
            return []
        label_ids = ent.labels or set()
    elif area_id is not None:
        area_reg = ar.async_get(hass)
        area = area_reg.async_get_area(area_id)
        if area is None:
            return []
        label_ids = area.labels or set()
    else:
        return []
    out: list[str] = []
    for lid in label_ids:
        lbl = label_reg.async_get_label(lid)
        if lbl is not None and lbl.name:
            out.append(lbl.name)
    return out


def _entities_with_label(hass: HomeAssistant, label_name_or_id: str) -> list[str]:
    """Return entity_ids carrying the label (matched by id or name)."""
    label_id = _resolve_label_id(hass, label_name_or_id)
    if label_id is None:
        return []
    ent_reg = er.async_get(hass)
    return [
        ent.entity_id
        for ent in ent_reg.entities.values()
        if ent.labels and label_id in ent.labels
    ]


def _areas_with_label(hass: HomeAssistant, label_name_or_id: str) -> list[str]:
    """Return area_ids carrying the label (matched by id or name)."""
    label_id = _resolve_label_id(hass, label_name_or_id)
    if label_id is None:
        return []
    area_reg = ar.async_get(hass)
    return [
        a.id
        for a in area_reg.async_list_areas()
        if a.labels and label_id in a.labels
    ]


def _floor_id_for_area(hass: HomeAssistant, area_id: str) -> str:
    """Return the floor_id for a given area, or '' if none."""
    area_reg = ar.async_get(hass)
    area = area_reg.async_get_area(area_id)
    if area is None or area.floor_id is None:
        return ""
    return area.floor_id


def _current_value_for_state(new_state: State | None) -> str:
    """Extract the raw current value from a state, honoring the event-domain shortcut."""
    if new_state is None:
        return ""
    if new_state.entity_id.split(".", 1)[0] == "event":
        et = new_state.attributes.get("event_type")
        if et:
            return str(et)
    return new_state.state if new_state.state is not None else ""


def _is_skip_value(cv_raw: str) -> bool:
    if _INITIAL_PRESS_RE.search(cv_raw):
        return True
    return cv_raw.lower() in UNKNOWN_STATES


