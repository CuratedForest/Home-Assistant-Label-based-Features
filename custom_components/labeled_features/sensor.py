async def async_setup_entry(
    hass: HomeAssistant,
    entry,
    async_add_entities,
) -> None:
    """Set up the labeled_features sensors."""
    manager: LabeledFeaturesManager = entry.runtime_data

    state_sensor = LabeledFeaturesStateSensor(manager)
    areas_sensor = LabeledFeatureAreasStateSensor(manager)

    async_add_entities([state_sensor, areas_sensor])

    # Register update callbacks with the manager
    manager.register_state_sensor_update_callback(state_sensor.async_write_ha_state)
    manager.register_areas_sensor_update_callback(areas_sensor.async_write_ha_state)


