def _normalize_suffix(raw: str | None) -> str | None:
    """Normalize and validate an entity ID suffix ('' or '_dev' style)."""
    value = (raw or "").strip().lower().replace(" ", "_").replace("-", "_")
    if value == "":
        return ""
    if not value.startswith("_"):
        value = f"_{value}"
    return value if _SUFFIX_RE.match(value) else None


def _title(suffix: str) -> str:
    """Config entry title."""
    return "Labeled Features" if suffix == "" else f"Labeled Features ({suffix})"


def _select(options: list[str], *, custom_value: bool = False) -> SelectSelector:
    """Dropdown selector helper."""
    return SelectSelector(
        SelectSelectorConfig(
            options=options,
            mode=SelectSelectorMode.DROPDOWN,
            custom_value=custom_value,
        )
    )


class LabeledFeaturesConfigFlow(ConfigFlow, domain=DOMAIN):
    """Handle a config flow for Labeled Features."""

    VERSION = 1

    def _suffix_in_use(self, suffix: str, ignore_entry_id: str | None = None) -> bool:
        """Return True when another entry already uses this suffix."""
        for entry in self._async_current_entries():
            if entry.entry_id == ignore_entry_id:
                continue
            if entry.data.get(CONF_SUFFIX, "") == suffix:
                return True
        return False

    async def async_step_user(
        self, user_input: dict[str, Any] | None = None
    ) -> ConfigFlowResult:
        """Handle the initial step."""
        errors: dict[str, str] = {}
        if user_input is not None:
            suffix = _normalize_suffix(user_input.get(CONF_SUFFIX))
            if suffix is None:
                errors["base"] = "invalid_suffix"
            elif self._suffix_in_use(suffix):
                return self.async_abort(reason="already_configured")
            else:
                return self.async_create_entry(
                    title=_title(suffix),
                    data={CONF_SUFFIX: suffix},
                )

        return self.async_show_form(
            step_id="user",
            data_schema=vol.Schema({vol.Optional(CONF_SUFFIX, default=""): str}),
            errors=errors or None,
        )

    async def async_step_reconfigure(
        self, user_input: dict[str, Any] | None = None
    ) -> ConfigFlowResult:
        """Allow changing the entity ID suffix."""
        entry = self._get_reconfigure_entry()
        errors: dict[str, str] = {}
        if user_input is not None:
            suffix = _normalize_suffix(user_input.get(CONF_SUFFIX))
            if suffix is None:
                errors["base"] = "invalid_suffix"
            elif self._suffix_in_use(suffix, ignore_entry_id=entry.entry_id):
                return self.async_abort(reason="already_configured")
            else:
                return self.async_update_reload_and_abort(
                    entry,
                    title=_title(suffix),
                    data={CONF_SUFFIX: suffix},
                )

        return self.async_show_form(
            step_id="reconfigure",
            data_schema=vol.Schema(
                {
                    vol.Optional(
                        CONF_SUFFIX,
                        default=entry.data.get(CONF_SUFFIX, ""),
                    ): str
                }
            ),
            errors=errors or None,
        )

    @staticmethod
    @callback
    def async_get_options_flow(config_entry: ConfigEntry) -> OptionsFlow:
        """Get the options flow."""
        return LabeledFeaturesOptionsFlow()

    @classmethod
    @callback
    def async_get_supported_subentry_types(
        cls, config_entry: ConfigEntry
    ) -> dict[str, type[ConfigSubentryFlow]]:
        """Return the supported subentry flows."""
        return {
            SUBENTRY_TYPE_LEADER: LeaderSubentryFlow,
            SUBENTRY_TYPE_PROVIDES: ProvidesSubentryFlow,
            SUBENTRY_TYPE_MODE: ModeSubentryFlow,
        }


class LabeledFeaturesOptionsFlow(OptionsFlow):
    """Handle options (error mode tiers)."""

    async def async_step_init(
        self, user_input: dict[str, Any] | None = None
    ) -> ConfigFlowResult:
        """Manage the options."""
        if user_input is not None:
            return self.async_create_entry(data=user_input)

        options = self.config_entry.options
        return self.async_show_form(
            step_id="init",
            data_schema=vol.Schema(
                {
                    vol.Optional(
                        CONF_ERROR_MODE,
                        default=options.get(CONF_ERROR_MODE, DEFAULT_ERROR_MODE),
                    ): _select(ERROR_MODES),
                    vol.Optional(
                        CONF_ALERT_ACTION,
                        default=options.get(CONF_ALERT_ACTION, DEFAULT_ALERT_ACTION),
                    ): str,
                    vol.Optional(
                        CONF_ALERT_SEVERITY,
                        default=options.get(
                            CONF_ALERT_SEVERITY, DEFAULT_ALERT_SEVERITY
                        ),
                    ): _select(SEVERITIES),
                }
            ),
        )


class _BaseSubentryFlow(ConfigSubentryFlow):
    """Shared helpers for the subentry flows."""

    def _unique_id_taken(self, unique_id: str) -> bool:
        """Return True when this entry already has a subentry with the id."""
        entry = self.hass.config_entries.async_get_known_entry(self.handler[0])
        return any(
            sub.unique_id == unique_id for sub in entry.subentries.values()
        )


class LeaderSubentryFlow(_BaseSubentryFlow):
    """Leader definition subentry (replaces Leader/modifier labels)."""

    def _schema(self, defaults: dict[str, Any]) -> vol.Schema:
        """Build the leader schema with defaults."""
        return vol.Schema(
            {
                vol.Required(
                    CONF_ENTITY_ID,
                    default=defaults.get(CONF_ENTITY_ID, vol.UNDEFINED),
                ): EntitySelector(),
                vol.Required(
                    SUBCONF_FEATURE,
                    default=defaults.get(SUBCONF_FEATURE, ""),
                ): str,
                vol.Required(
                    SUBCONF_SCOPE,
                    default=defaults.get(SUBCONF_SCOPE, SCOPE_AREA),
                ): _select(LEADER_SCOPES),
                vol.Optional(
                    SUBCONF_ENABLE_VALUE,
                    default=defaults.get(SUBCONF_ENABLE_VALUE, ""),
                ): str,
                vol.Optional(
                    SUBCONF_DISABLE_VALUE,
                    default=defaults.get(SUBCONF_DISABLE_VALUE, ""),
                ): str,
                vol.Optional(
                    SUBCONF_DIRECTION,
                    default=defaults.get(SUBCONF_DIRECTION, DIRECTION_NONE),
                ): _select(DIRECTIONS),
                vol.Optional(
                    SUBCONF_INVERT,
                    default=defaults.get(SUBCONF_INVERT, False),
                ): bool,
            }
        )

    async def async_step_user(
        self, user_input: dict[str, Any] | None = None
    ) -> SubentryFlowResult:
        """Add a leader definition."""
        if user_input is not None:
            feature = user_input[SUBCONF_FEATURE].strip()
            user_input[SUBCONF_FEATURE] = feature
            unique_id = (
                f"{user_input[CONF_ENTITY_ID]}|{feature}|{user_input[SUBCONF_SCOPE]}"
            )
            if self._unique_id_taken(unique_id):
                return self.async_abort(reason="already_configured")
            return self.async_create_entry(
                title=f"{feature} ({user_input[CONF_ENTITY_ID]})",
                data=user_input,
                unique_id=unique_id,
            )
        return self.async_show_form(step_id="user", data_schema=self._schema({}))

    async def async_step_reconfigure(
        self, user_input: dict[str, Any] | None = None
    ) -> SubentryFlowResult:
        """Edit a leader definition."""
        subentry = self._get_reconfigure_subentry()
        if user_input is not None:
            feature = user_input[SUBCONF_FEATURE].strip()
            user_input[SUBCONF_FEATURE] = feature
            return self.async_update_and_abort(
                self._get_reconfigure_entry(),
                subentry,
                title=f"{feature} ({user_input[CONF_ENTITY_ID]})",
                data=user_input,
                unique_id=f"{user_input[CONF_ENTITY_ID]}|{feature}|{user_input[SUBCONF_SCOPE]}",
            )
        return self.async_show_form(
            step_id="reconfigure",
            data_schema=self._schema(dict(subentry.data)),
        )


