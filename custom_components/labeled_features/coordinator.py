    def _eval_leader(
        self,
        eid: str,
        fname: str,
        scope_pfx: str,
        cv: str,
        prev_cv: str,
    ) -> bool:
        """Evaluate whether a leader enables a feature.

        Matches the template sensor's eval_leader macro:
        1. Direction (Increasing/Decreasing) takes precedence
        2. Enable/Disable labels
        3. Default truth (state == feature_name or truthy)
        4. event/button domains always True
        5. Invert applied last
        """
        label_names = self._get_entity_label_names(eid)
        state_obj = self.hass.states.get(eid)
        state_str = state_obj.state if state_obj else ""
        dom = eid.split(".")[0]

        inc_lbl = f"{scope_pfx}{fname} Increasing: True" in label_names
        dec_lbl = f"{scope_pfx}{fname} Decreasing: True" in label_names

        if inc_lbl or dec_lbl:
            cur_n = float(cv) if cv else None
            prev_n = float(prev_cv) if prev_cv else None
            if cur_n is not None and prev_n is not None:
                is_inc = cur_n > prev_n
                is_dec = cur_n < prev_n
                base = (inc_lbl and is_inc) or (dec_lbl and is_dec)
            else:
                base = False
        else:
            en_lbl = ""
            dis_lbl = ""
            for lbl in label_names:
                if lbl.startswith(f"{scope_pfx}{fname} Enable: "):
                    en_lbl = lbl[len(f"{scope_pfx}{fname} Enable: "):].strip()
                if lbl.startswith(f"{scope_pfx}{fname} Disable: "):
                    dis_lbl = lbl[len(f"{scope_pfx}{fname} Disable: "):].strip()
            if en_lbl or dis_lbl:
                by_en = en_lbl and state_str == en_lbl
                by_dis = dis_lbl and state_str == dis_lbl
                if en_lbl and dis_lbl:
                    base = by_en and not by_dis
                elif en_lbl:
                    base = by_en
                else:
                    base = not by_dis
            else:
                if dom in BUTTON_DOMAINS:
                    base = True
                else:
                    base = (state_str == fname) or (
                        state_str.lower() in STATE_TRUTHY
                    )

        inverted = f"{scope_pfx}{fname} Invert: True" in label_names
        return (not base) if inverted else base

