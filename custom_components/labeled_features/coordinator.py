    def _rebuild_features(self, _event_data: dict | None) -> None:
        """Rebuild features state from scratch (full rebuild)."""
        all_leaders = self._resolve_label_entities(self.feature_leader_label)
        triples = self._build_triple_map(all_leaders)
        modes = self._resolve_modes(all_leaders, triples)
        prev_features = self._features

        result: dict[str, Any] = {}
        for key, leaders_list in triples.items():
            parts = key.split(LABEL_MAP_SEPARATOR)
            if len(parts) != 3:
                continue
            fname, scope_val, scope_id_val = parts
            scope_pfx = (
                "Area " if scope_val == SCOPE_AREA
                else ("Floor " if scope_val == SCOPE_FLOOR else "")
            )
            mode = modes.get(key, MODE_LEADER)

            values: list[bool] = []
            triggering_eid = ""
            for eid in leaders_list:
                state_obj = self.hass.states.get(eid)
                if state_obj is None:
                    values.append(False)
                    continue
                cv = state_obj.state
                prev_cv = self._leaders.get(eid, {}).get("previous_value", "")
                truth = self._eval_leader(
                    eid, fname, scope_pfx, cv, prev_cv
                )
                values.append(truth)
                if truth:
                    triggering_eid = eid

            if mode == MODE_LEADER:
                new_enabled = any(values)
            elif mode == MODE_ALL:
                new_enabled = min(values) if values else False
            else:
                new_enabled = max(values) if values else False

            prev_entry = (
                prev_features.get(fname, {})
                .get(scope_val, {})
                .get(scope_id_val, {})
                if isinstance(
                    prev_features.get(fname, {}).get(scope_val, {}), dict
                )
                else {}
            )
            prev_ts = (
                prev_entry.get("last_changed_timestamp", 0)
                if isinstance(prev_entry, dict)
                else 0
            )

            new_entry = {
                "enabled": new_enabled,
                "mode": mode,
                "last_changed_timestamp": prev_ts,
                "triggering_leader": triggering_eid,
            }

            result.setdefault(fname, {}).setdefault(
                scope_val, {}
            )[scope_id_val] = new_entry

        # Carry through manual overrides
        for fname, scopes_map in prev_features.items():
            if not isinstance(scopes_map, dict):
                continue
            for scope_val, sids in scopes_map.items():
                if not isinstance(sids, dict):
                    continue
                for scope_id_val, entry in sids.items():
                    if not isinstance(entry, dict):
                        continue
                    if entry.get("triggering_leader", "") != "":
                        continue
                    key = f"{fname}{LABEL_MAP_SEPARATOR}{scope_val}{LABEL_MAP_SEPARATOR}{scope_id_val}"
                    if key not in triples:
                        result.setdefault(fname, {}).setdefault(
                            scope_val, {}
                        )[scope_id_val] = entry

        self._features = result

    def _process_state_changed(
        self, changed_eid: str, new_state: State | None
    ) -> None:
        """Process a state change for a single leader entity."""
        if new_state is None:
            return

        all_leaders = self._resolve_label_entities(self.feature_leader_label)
        if changed_eid not in all_leaders:
            return

        triples = self._build_triple_map(all_leaders)
        modes = self._resolve_modes(all_leaders, triples)
        prev_features = self._features

        dom = new_state.entity_id.split(".")[0]
        cv_raw = (
            new_state.attributes.get("event_type", new_state.state)
            if dom in ("event", "button")
            else new_state.state
        )
        is_skip = (
            "_initial_press" in cv_raw
            or cv_raw.lower() in STATE_UNAVAILABLE
        )
        if is_skip:
            self._features = self._carry_through(prev_features, triples)
            return

        ts = (
            new_state.last_changed.timestamp()
            if new_state.last_changed
            else 0
        )
        prev_l = self._leaders.get(changed_eid, {})
        prev_cv = prev_l.get("current_value", "")

        result = self._carry_through(prev_features, triples)

        for key, leaders_list in triples.items():
            if changed_eid not in leaders_list:
                continue
            parts = key.split(LABEL_MAP_SEPARATOR)
            if len(parts) != 3:
                continue
            fname, scope_val, scope_id_val = parts
            scope_pfx = (
                "Area " if scope_val == SCOPE_AREA
                else ("Floor " if scope_val == SCOPE_FLOOR else "")
            )
            mode = modes.get(key, MODE_LEADER)

            this_truth = self._eval_leader(
                changed_eid, fname, scope_pfx, cv_raw, prev_cv
            )

            if mode == MODE_LEADER:
                new_enabled = this_truth
            else:
                values: list[bool] = []
                for other_eid in leaders_list:
                    if other_eid == changed_eid:
                        values.append(this_truth)
                    else:
                        other_state = self.hass.states.get(other_eid)
                        other_cv = other_state.state if other_state else ""
                        other_prev = self._leaders.get(
                            other_eid, {}
                        ).get("previous_value", "")
                        other_truth = self._eval_leader(
                            other_eid, fname, scope_pfx, other_cv, other_prev
                        )
                        values.append(other_truth)
                new_enabled = (
                    min(values) if mode == MODE_ALL else max(values)
                )

            existing_f = result.get(fname, {})
            existing_s = existing_f.get(scope_val, {})
            prev_entry = (
                existing_s.get(scope_id_val, {})
                if isinstance(existing_s, dict)
                else {}
            )
            prev_enabled = (
                prev_entry.get("enabled")
                if isinstance(prev_entry, dict)
                else None
            )
            prev_ts = (
                prev_entry.get("last_changed_timestamp", ts)
                if isinstance(prev_entry, dict)
                else ts
            )

            is_button = dom in BUTTON_DOMAINS
            flipped = (
                (prev_enabled is None)
                or (prev_enabled != new_enabled)
                or is_button
            )
            new_ts = ts if flipped else prev_ts

            new_entry = {
                "enabled": new_enabled,
                "mode": mode,
                "last_changed_timestamp": new_ts,
                "triggering_leader": changed_eid,
            }

            result.setdefault(fname, {}).setdefault(
                scope_val, {}
            )[scope_id_val] = new_entry

        self._features = result

    def _build_triple_map(
        self, all_leaders: list[str]
    ) -> dict[str, list[str]]:
        """Build mapping of (feature, scope, scope_id) -> [leader_entity_ids]."""
        triples: dict[str, list[str]] = {}
        for eid in all_leaders:
            label_names = self._get_entity_label_names(eid)
            aid = self._get_area_id(eid)
            fid = self._get_floor_id_for_area(aid) if aid else ""
            for lbl in label_names:
                matched = False
                for prefix, scope_val, scope_id_fn in (
                    ("Area Leader: ", SCOPE_AREA, lambda: aid),
                    ("Floor Leader: ", SCOPE_FLOOR, lambda: fid),
                ):
                    if lbl.startswith(prefix):
                        fname = lbl[len(prefix):].strip()
                        if not fname:
                            continue
                        scope_id_val = scope_id_fn()
                        if not scope_id_val:
                            continue
                        key = f"{fname}{LABEL_MAP_SEPARATOR}{scope_val}{LABEL_MAP_SEPARATOR}{scope_id_val}"
                        triples.setdefault(key, [])
                        if eid not in triples[key]:
                            triples[key].append(eid)
                        matched = True
                        break
                if not matched and lbl.startswith("Leader: "):
                    fname = lbl[len("Leader: "):].strip()
                    if fname:
                        key = f"{fname}{LABEL_MAP_SEPARATOR}{SCOPE_GLOBAL}{LABEL_MAP_SEPARATOR}"
                        triples.setdefault(key, [])
                        if eid not in triples[key]:
                            triples[key].append(eid)
        return triples

    def _resolve_modes(
        self, _all_leaders: list[str], triples: dict[str, list[str]]
    ) -> dict[str, str]:
        """Resolve mode for each (feature, scope, scope_id) triple."""
        modes: dict[str, str] = {}
        for key in triples:
            parts = key.split(LABEL_MAP_SEPARATOR)
            if len(parts) != 3:
                continue
            fname, scope_val, _scope_id_val = parts
            scope_pfx = (
                "Area " if scope_val == SCOPE_AREA
                else ("Floor " if scope_val == SCOPE_FLOOR else "")
            )
            mode_val = MODE_LEADER
            for lbl in self._get_sensor_label_names():
                expected = f"{scope_pfx}{fname} Mode: "
                if lbl.startswith(expected):
                    mv = lbl[len(expected):].strip().lower()
                    if mv in FEATURE_MODES:
                        mode_val = mv
                        break
            modes[key] = mode_val
        return modes

    def _get_sensor_label_names(self) -> list[str]:
        """Get labels on the sensor entity itself."""
        try:
            reg = er.async_get(self.hass)
            suffix = self._entry.data.get(CONF_ENTITY_ID_SUFFIX, "")
            uid = f"labeled_features_state{suffix}"
            entry = reg.async_get_entity_id("sensor", "labeled_features", uid)
            if entry:
                er_entry = reg.async_get(entry)
                if er_entry and er_entry.labels:
                    return self._resolve_label_ids(er_entry.labels)
        except Exception:
            pass
        return []

    def _handle_manual_override(
        self, prev_features: dict, event_data: dict
    ) -> dict:
        """Handle a manual feature set event."""
        tgt = event_data.get("target_feature", "").strip()
        scp = event_data.get("scope", "").lower().strip()
        sid = str(event_data.get("scope_id", ""))
        ena = bool(event_data.get("enabled", False))
        ts = float(event_data.get("timestamp", 0)) or 0

        result = dict(prev_features)
        if tgt and scp in (SCOPE_AREA, SCOPE_FLOOR, SCOPE_GLOBAL):
            existing_f = result.get(tgt, {})
            existing_s = existing_f.get(scp, {})
            prev_entry = (
                existing_s.get(sid, {})
                if isinstance(existing_s, dict)
                else {}
            )
            _mode = (
                prev_entry.get("mode", MODE_LEADER)
                if isinstance(prev_entry, dict)
                else MODE_LEADER
            )
            new_entry = {
                "enabled": ena,
                "mode": _mode,
                "last_changed_timestamp": ts or 0,
                "triggering_leader": "",
            }
            result.setdefault(tgt, {}).setdefault(scp, {})[
                sid
            ] = new_entry
        return result

    def _carry_through(
        self, prev_features: dict, triples: dict[str, list[str]]
    ) -> dict:
        """Carry through existing features, dropping orphans."""
        result: dict[str, Any] = {}
        for fname, scopes_map in prev_features.items():
            if not isinstance(scopes_map, dict):
                continue
            for scope_val, sids in scopes_map.items():
                if not isinstance(sids, dict):
                    continue
                for scope_id_val, entry in sids.items():
                    if not isinstance(entry, dict):
                        continue
                    key = f"{fname}{LABEL_MAP_SEPARATOR}{scope_val}{LABEL_MAP_SEPARATOR}{scope_id_val}"
                    has_leader = key in triples
                    is_manual = entry.get("triggering_leader", "") == ""
                    if has_leader or is_manual:
                        result.setdefault(fname, {}).setdefault(
                            scope_val, {}
                        )[scope_id_val] = entry
        return result

