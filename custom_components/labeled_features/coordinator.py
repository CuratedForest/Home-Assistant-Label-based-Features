"""Coordinators for the Labeled Features integration.

Event-driven (push) coordinators holding the two sensors' state. They listen
to the same event surface the legacy trigger-based template sensors used:

  FeaturesCoordinator — state_changed (feature_leader ∪ subentry leaders,
    with the legacy boot-noise gate), labeled_feature_set,
    labeled_feature_snapshot_set; registry events refresh the leader cache.
  AreasCoordinator — label/area/floor registry updates + homeassistant.start.

Recomputation runs through the pure functions in engine.py; errors route
through error_handler (self-clearing Repair issues).

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

import logging
