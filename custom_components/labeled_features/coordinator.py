    @callback
    def _on_state_changed(self, event: Event) -> None:
        """Handle state change events for feature leaders (gated)."""
        eid = event.data.get("entity_id", "")
        if not eid:
            return

        old_state = event.data.get("old_state")

        # Gate: reject if entity is not a feature leader AND not a known
        # stale leader (label was removed).
        if not self._is_feature_leader(eid):
            if eid not in self._leaders:
                return
            # Stale leader: label was removed, clean up
            self._leaders.pop(eid, None)
            self._features = self._carry_through(
                self._features,
                self._build_triple_map(
                    self._resolve_label_entities(self.feature_leader_label)
                ),
            )
            self.async_set_updated_data(self._build_coordinator_data())
            return

        # Gate: reject boot-restore noise (no old state or old state was
        # unavailable).
        if old_state is None:
            return
        old_str = str(getattr(old_state, "state", "")).lower()
        if old_str in STATE_UNAVAILABLE:
            return

        new_state = event.data.get("new_state")
        self._update_leader_state(eid, new_state)
        self._process_state_changed(eid, new_state)
        self.async_set_updated_data(self._build_coordinator_data())

