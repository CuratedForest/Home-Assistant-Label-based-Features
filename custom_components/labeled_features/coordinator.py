    def _is_feature_leader(self, entity_id: str) -> bool:
        """Check if entity carries the feature_leader label."""
        try:
            reg = er.async_get(self.hass)
            entry = reg.async_get(entity_id)
            if entry and entry.labels:
                return self.feature_leader_label in entry.labels
        except Exception:
            pass
        return False

    def _get_entity_label_names(self, entity_id: str) -> list[str]:
        """Get label names for an entity."""
        try:
            reg = er.async_get(self.hass)
            entry = reg.async_get(entity_id)
            if not entry or not entry.labels:
                return []
            return self._resolve_label_ids(entry.labels)
        except Exception:
            return []

    def _get_area_label_names(self, area_id: str) -> list[str]:
        """Get label names attached directly to an area."""
        try:
            areg = ar.async_get(self.hass)
            area = areg.async_get(area_id)
            if not area or not area.labels:
                return []
            return self._resolve_label_ids(area.labels)
        except Exception:
            return []

    def _resolve_label_ids(self, label_ids: set[str]) -> list[str]:
        """Resolve label IDs to their names."""
        try:
            lr = label_helper.async_get(self.hass)
        except Exception:
            return []
        result: list[str] = []
        for lid in label_ids:
            try:
                lbl = lr.async_get(lid)
                if lbl:
                    result.append(lbl.name)
            except Exception:
                continue
        return result

    def _get_area_id(self, entity_id: str) -> str:
        """Get area ID for an entity."""
        try:
            reg = er.async_get(self.hass)
            entry = reg.async_get(entity_id)
            if entry and entry.area_id:
                return entry.area_id
        except Exception:
            pass
        return ""

    def _get_floor_id_for_area(self, area_id: str) -> str:
        """Get floor ID for an area."""
        try:
            areg = ar.async_get(self.hass)
            area = areg.async_get(area_id)
            if area and area.floor_id:
                return area.floor_id
        except Exception:
            pass
        return ""

    def _resolve_label_entities(self, label_name: str) -> list[str]:
        """Resolve entity IDs for a label name."""
        try:
            reg = er.async_get(self.hass)
            lr = label_helper.async_get(self.hass)
        except Exception:
            return []
        result: list[str] = []
        for entry in reg.entities.values():
            if entry.labels:
                for lid in entry.labels:
                    try:
                        lbl = lr.async_get(lid)
                        if lbl and lbl.name == label_name:
                            result.append(entry.entity_id)
                            break
                    except Exception:
                        continue
        return result

    def _resolve_label_areas(self, label_name: str) -> list[str]:
        """Resolve area IDs that have the label directly attached."""
        try:
            areg = ar.async_get(self.hass)
            lr = label_helper.async_get(self.hass)
        except Exception:
            return []
        result: list[str] = []
        for area in areg.async_list_areas():
            if area.labels:
                for lid in area.labels:
                    try:
                        lbl = lr.async_get(lid)
                        if lbl and lbl.name == label_name:
                            result.append(area.id)
                            break
                    except Exception:
                        continue
        return result

