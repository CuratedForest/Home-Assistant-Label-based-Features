    def _rebuild_label_map(self) -> None:
        """Rebuild the label_map for area-based features."""
        leader_areas = self._resolve_label_areas(self.feature_leader_label)

        scopes: dict[str, dict] = {}
        for aid in leader_areas:
            floor_id = ""
            try:
                areg = ar.async_get(self.hass)
                area = areg.async_get(aid)
                if area and area.floor_id:
                    floor_id = area.floor_id
            except Exception:
                pass
            scopes[aid] = {
                "kind": "area",
                "floor_id": floor_id,
                "labels": {},
            }

        for aid in leader_areas:
            area_lbl_names = self._get_area_label_names(aid)
            floor_id = scopes[aid]["floor_id"]

            for lbl in area_lbl_names:
                m = re.match(
                    r"^(Area|Floor|)Provides:\s*(.+)$", lbl
                )
                if not m:
                    continue

                prefix = m.group(1)
                lname = m.group(2).strip()
                if not lname:
                    continue

                is_modifier = any(
                    lname.endswith(kw) or (
                        f" {kw}" in lname
                    )
                    for kw in MODIFIER_LABEL_KEYWORDS
                )
                if is_modifier:
                    continue

                scope_val = (
                    SCOPE_AREA if prefix == "Area"
                    else (SCOPE_FLOOR if prefix == "Floor" else "none")
                )
                scope_id_val = (
                    aid
                    if scope_val in (SCOPE_AREA, "none")
                    else floor_id
                )
                if not scope_id_val:
                    continue

                scope_prefix = (
                    "Area " if scope_val == SCOPE_AREA
                    else ("Floor " if scope_val == SCOPE_FLOOR else "")
                )
                comp_override = ""
                comp_pat = (
                    f"{scope_prefix}Provides {lname} Component: "
                )
                for lbl2 in area_lbl_names:
                    if lbl2.startswith(comp_pat):
                        comp_override = lbl2[len(comp_pat):].strip()
                        break

                component = comp_override or COMPONENT_DEFAULT

                lentry = {
                    "scope": scope_val,
                    "scope_id": scope_id_val,
                    "component": component,
                    "declaring_area_id": aid,
                }

                if scope_id_val not in scopes:
                    scopes[scope_id_val] = {
                        "kind": "floor",
                        "floor_id": scope_id_val,
                        "labels": {},
                    }

                if lname not in scopes[scope_id_val].get("labels", {}):
                    scopes[scope_id_val]["labels"][lname] = lentry

        label_map: dict[str, Any] = {}
        for sid, sdat in scopes.items():
            for lname, ldat in sdat.get("labels", {}).items():
                key = f"{sid}{LABEL_MAP_SEPARATOR}{lname}"
                label_map[key] = {
                    "scope_id": sid,
                    "label": lname,
                    "scope": ldat.get("scope", SCOPE_AREA),
                    "component": ldat.get("component"),
                    "declaring_area_id": ldat.get("declaring_area_id"),
                    "label_data": ldat,
                }

        self._label_map = label_map

