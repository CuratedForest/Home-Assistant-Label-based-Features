from homeassistant.core import Event, HomeAssistant
from homeassistant.helpers import (
    area_registry as ar,
    device_registry as dr,
    entity_registry as er,
    floor_registry as fr,  # noqa: F401  (kept for parity w/ registry surface)
    label_registry as lr,
)
from homeassistant.helpers.update_coordinator import DataUpdateCoordinator
from homeassistant.util import dt as dt_util

from . import engine
from .const import (
    AREAS_SENSOR_STEM,
    DOMAIN,
    EVENT_LABELED_FEATURE_SET,
    EVENT_LABELED_FEATURE_SNAPSHOT_SET,
    FEATURES_SENSOR_STEM,
    LABEL_FEATURE_LEADER,
    SKIP_STATES,
    SUBCONF_AREA_ID,
    SUBCONF_ENTITY_ID,
    SUBENTRY_TYPE_LEADER,
    SUBENTRY_TYPE_MODE,
    SUBENTRY_TYPE_PROVIDES,
)
