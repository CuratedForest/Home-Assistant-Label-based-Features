    def _handle_snapshot_set(self, event_data: dict) -> None:
        """Handle a snapshot set event."""
        sname = event_data.get("snapshot_name", "").strip()
        payload_raw = event_data.get("payload")
        if not sname:
            return
        if payload_raw is None or (
            isinstance(payload_raw, dict) and len(payload_raw) == 0
        ):
            self._snapshots.pop(sname, None)
        elif isinstance(payload_raw, dict):
            self._snapshots[sname] = payload_raw