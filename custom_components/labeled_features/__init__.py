    async def _on_state_changed(self, event: Event) -> None:
        """Handle state_changed events."""
        event_data: EventStateChangedData = event.data
        entity_id = event_data.get("entity_id", "")
        old_state = event_data.get("old_state")

        # Check if this entity is a feature_leader
        all_leader_entities = self._get_feature_leader_entities()

        if entity_id not in all_leader_entities:
            return

        # Skip events with no real prior state (boot restore, reconnection)
        if old_state is None or (
            old_state.state.lower() in ["unknown", "unavailable", "none"]
        ):
            return

        # Rebuild state
        self._recompute_leaders(entity_id)
        self._recompute_features(entity_id, "state_changed")
        self._notify_state_sensors()
        self._notify_areas_sensors()

    async def _on_registry_updated(self, event: Event) -> None:
        """Handle registry update events (label, area, floor)."""
        self._recompute_all()
        self._notify_state_sensors()
        self._notify_areas_sensors()

