    async def async_handle_manual_set(
        self,
        target_feature: str,
        scope: str,
        scope_id: str,
        enabled: bool,
        timestamp: float,
    ) -> None:
        """Handle a manual feature set event."""
        if not target_feature or scope not in ("area", "floor", "global"):
            return

        # Carry through existing entries
        prev_features_raw = self._features
        if not isinstance(prev_features_raw, dict):
            prev_features_raw = {}

        ns_result: dict[str, dict[str, dict[str, dict[str, Any]]]] = {}

        for fname, scopes_map in prev_features_raw.items():
            if not isinstance(scopes_map, dict):
                continue
            for scope_val, sids in scopes_map.items():
                if not isinstance(sids, dict):
                    continue
                for sid, entry in sids.items():
                    if not isinstance(entry, dict):
                        continue
                    ns_result.setdefault(fname, {}).setdefault(
                        scope_val, {}
                    )[sid] = entry

        # Write the manual override
        prev_entry = (
            ns_result.get(target_feature, {})
            .get(scope, {})
            .get(scope_id, {})
        )
        mode = prev_entry.get("mode", "leader")

        ns_result.setdefault(target_feature, {}).setdefault(
            scope, {}
        )[scope_id] = {
            "enabled": enabled,
            "mode": mode,
            "last_changed_timestamp": timestamp,
            "triggering_leader": "",
        }

        self._features = ns_result
        self._notify_state_sensors()

    # ------------------------------------------------------------------
    # Snapshots attribute computation
    # ------------------------------------------------------------------

    def async_handle_snapshot_set(
        self, snapshot_name: str, payload: dict[str, Any]
    ) -> None:
        """Handle a snapshot set event (Set Snapshot catalog entry).

        Updates the snapshots attribute and notifies sensors.
        Empty payload deletes the entry.
        """
        if not snapshot_name:
            return

        prev = self._snapshots if isinstance(self._snapshots, dict) else {}

        if not isinstance(payload, dict) or len(payload) == 0:
            # Delete the entry
            prev.pop(snapshot_name, None)
        else:
            prev[snapshot_name] = payload

        self._snapshots = prev
        self._notify_state_sensors()

    # ------------------------------------------------------------------
    # Label map (areas state)
    # ------------------------------------------------------------------

    def _recompute_label_map(self) -> None:
        """Recompute the label_map attribute for areas_state sensor.

        Matches the Jinja2 template exactly.
        Uses registries directly (no async calls).
        """
        # Pass 1: Build empty scope skeleton for every area gated by feature_leader
        leader_entity_ids = self._get_feature_leader_entities()
        areas_with_leaders = set()
        for eid in leader_entity_ids:
            aid = self._get_area_id(eid)
            if aid.strip():
                areas_with_leaders.add(aid.strip())

        # Pass 2: Parse each gated area's labels for (Area|Floor)Provides: <Label>
        scopes: dict[str, dict[str, Any]] = {}
        for aid in areas_with_leaders:
            fid = _compute_floor_id(self.hass, aid)
            scopes[aid] = {
                "kind": "area",
                "floor_id": fid,
                "labels": {},
            }

        # Parse area labels for Provides: declarations
        area_reg = ar.async_get(self.hass)
        modifier_re = re.compile(MODIFIER_LABEL_PATTERN)

        for aid in areas_with_leaders:
            area = area_reg.areas.get(aid)
            if area is None:
                continue

            area_lbls = list(area.labels) if area.labels else []
            this_floor_id = scopes[aid]["floor_id"]

            for lbl in area_lbls:
                m = PROVIDES_RE.match(lbl)
                if not m:
                    continue

                prefix = m.group(1).strip()
                lname = m.group(2).strip()

                # Skip modifier labels
                if modifier_re.match(lname):
                    continue

                if lname == "":
                    continue

                scope_val = (
                    "area"
                    if prefix == "Area"
                    else ("floor" if prefix == "Floor" else "none")
                )
                scope_id_val = (
                    aid
                    if scope_val in ("area", "none")
                    else this_floor_id
                )

                if scope_id_val == "":
                    continue

                # Component hint
                scope_prefix = (
                    "Area "
                    if scope_val == "area"
                    else ("Floor " if scope_val == "floor" else "")
                )
                comp_override = ""
                comp_pattern_prefix = (
                    scope_prefix + "Provides " + lname + " Component: "
                )
                for area_lbl in area_lbls:
                    if area_lbl.startswith(comp_pattern_prefix):
                        comp_override = area_lbl[
                            len(comp_pattern_prefix):
                        ].strip()
                        break
                component = comp_override if comp_override else "select"

                lentry = {
                    "scope": scope_val,
                    "scope_id": scope_id_val,
                    "component": component,
                    "declaring_area_id": aid,
                }

                if scope_id_val not in scopes:
                    scopes[scope_id_val] = {
                        "kind": "floor",
                        "floor_id": scope_id_val,
                        "labels": {lname: lentry},
                    }
                else:
                    existing = scopes[scope_id_val]
                    if lname not in existing.get("labels", {}):
                        labels = dict(existing.get("labels", {}))
                        labels[lname] = lentry
                        existing["labels"] = labels

        # Flatten to public <scope_id>||<label> → label_data map
        fns: dict[str, dict[str, Any]] = {}
        for sid, sdat in scopes.items():
            for lname, ldat in sdat.get("labels", {}).items():
                fns[f"{sid}||{lname}"] = {
                    "scope_id": sid,
                    "label": lname,
                    "scope": ldat.get("scope", "area"),
                    "component": ldat.get("component"),
                    "declaring_area_id": ldat.get("declaring_area_id"),
                    "label_data": ldat,
                }

        self._label_map = fns

    # ------------------------------------------------------------------
    # Error handling
    # ------------------------------------------------------------------

    async def async_handle_error(
        self,
        error_mode: str,
        message: str,
        source: str = "Labeled Features",
        severity: str = "medium",
    ) -> None:
        """Handle errors per the Error Mode tiers.

        Matches script.labeled_feature_error_mode behavior exactly.

        Tiers:
        - silent: no-op
        - log: system_log.write at warning
        - alert: script.send_alert
        - stop: system_log.write at error (caller must do stop: error: true)
        """
        if error_mode not in SUPPORTED_ERROR_MODES:
            error_mode = self._error_mode_default

        if error_mode == "silent":
            pass
        elif error_mode == "log":
            await self.hass.services.async_call(
                "system_log",
                "write",
                {
                    "level": "warning",
                    "message": f"{source}: {message}",
                },
                blocking=True,
            )
        elif error_mode == "alert":
            alert_script = self._alert_script
            if alert_script:
                await self.hass.services.async_call(
                    "script",
                    "send_alert",
                    {
                        "alert_severity": severity,
                        "alert_title": source,
                        "alert_message": message,
                    },
                    blocking=True,
                )
        elif error_mode == "stop":
            await self.hass.services.async_call(
                "system_log",
                "write",
                {
                    "level": "error",
                    "message": f"{source}: {message}",
                },
                blocking=True,
            )

