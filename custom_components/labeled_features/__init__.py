"""The Labeled Features integration.

Replaces the legacy trigger-based template sensors
(sensor.labeled_features_state and sensor.labeled_feature_areas_state) with
native, byte-compatible sensors, and adds tiered error handling.

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""

from __future__ import annotations

from dataclasses import dataclass

from homeassistant.config_entries import ConfigEntry
from homeassistant.core import HomeAssistant
from homeassistant.helpers import issue_registry as ir

from .const import CONF_SUFFIX, DOMAIN, PLATFORMS
from .coordinator import AreasCoordinator, FeaturesCoordinator
from .services import (
    _loaded_entries,
    async_register_services,
    async_unregister_services,
)


@dataclass
class LabeledFeaturesRuntimeData:
    """Runtime data stored on the config entry."""

    features_coordinator: FeaturesCoordinator
    areas_coordinator: AreasCoordinator


type LabeledFeaturesConfigEntry = ConfigEntry[LabeledFeaturesRuntimeData]


async def async_setup_entry(hass: HomeAssistant, entry: LabeledFeaturesConfigEntry) -> bool:
    """Set up Labeled Features from a config entry."""
    suffix = entry.data.get(CONF_SUFFIX, "")
    features_coordinator = FeaturesCoordinator(hass, entry, suffix)
    areas_coordinator = AreasCoordinator(hass, entry, suffix)
    entry.runtime_data = LabeledFeaturesRuntimeData(
        features_coordinator=features_coordinator,
        areas_coordinator=areas_coordinator,
    )

    _loaded_entries(hass)[entry.entry_id] = suffix
    entry.async_on_unload(lambda: _loaded_entries(hass).pop(entry.entry_id, None))

    await features_coordinator.async_setup()
    await areas_coordinator.async_setup()

    async_register_services(hass)
    entry.async_on_unload(entry.add_update_listener(_async_update_listener))

    await hass.config_entries.async_forward_entry_setups(entry, PLATFORMS)
    return True


async def _async_update_listener(
    hass: HomeAssistant, entry: LabeledFeaturesConfigEntry
) -> None:
    """Reload the entry when options/subentries change."""
    await hass.config_entries.async_reload(entry.entry_id)


async def async_unload_entry(
    hass: HomeAssistant, entry: LabeledFeaturesConfigEntry
) -> bool:
    """Unload a config entry."""
    if unload_ok := await hass.config_entries.async_unload_platforms(
        entry, PLATFORMS
    ):
        _loaded_entries(hass).pop(entry.entry_id, None)
        if not _loaded_entries(hass):
            async_unregister_services(hass)
    return unload_ok


async def async_remove_entry(
    hass: HomeAssistant, entry: LabeledFeaturesConfigEntry
) -> None:
    """Remove a config entry (clear its Repair issues)."""
    issue_registry = ir.async_get(hass)
    for issue_domain, issue_id in list(issue_registry.issues):
        if issue_domain == DOMAIN and issue_id.startswith(entry.entry_id):
            ir.async_delete_issue(hass, DOMAIN, issue_id)
