    # Features attribute computation
    # ------------------------------------------------------------------

    def _recompute_features(
        self, changed_eid: str = "", evtype: str = ""
    ) -> None:
        """Recompute the features attribute.

        Matches the Jinja2 template exactly.
        """
        all_leader_entities = self._get_feature_leader_entities()

        # Defensive: coerce legacy schema
        prev_features_raw = self._features
        if not isinstance(prev_features_raw, dict):
            prev_features_raw = {}

        # Step 1: Build triples map: (feature, scope, scope_id) → [leader entity_ids]
        triples: dict[str, list[str]] = {}
        for eid in all_leader_entities:
            aid = self._get_area_id(eid)
            aid = aid.strip()
            fid = _compute_floor_id(self.hass, aid) if aid else ""

            entity_labels = self._get_entity_labels(eid)
            for lbl in entity_labels:
                m = LEADER_RE.match(lbl)
                if not m:
                    continue
                prefix = m.group(1).strip()
                fname = m.group(2).strip()

                if prefix == "Area":
                    scope_val = "area"
                elif prefix == "Floor":
                    scope_val = "floor"
                else:
                    scope_val = "global"

                if scope_val == "area" and aid == "":
                    continue
                if scope_val == "floor" and fid == "":
                    continue

                scope_id_val = (
                    aid
                    if scope_val == "area"
                    else (fid if scope_val == "floor" else "")
                )

                if scope_val == "area" and scope_id_val == "":
                    continue

                key = f"{fname}||{scope_val}||{scope_id_val}"
                if key not in triples:
                    triples[key] = []
                if eid not in triples[key]:
                    triples[key].append(eid)

        # Step 2: Resolve mode for each triple from sensor labels
        sensor_labels = self._get_entity_labels("sensor.labeled_features_state")
        mode_for: dict[str, str] = {}
        for key in triples.keys():
            parts = key.split("||")
            fname = parts[0]
            scope_val = parts[1]
            scope_pfx = (
                "Area "
                if scope_val == "area"
                else ("Floor " if scope_val == "floor" else "")
            )

            mode_found = "leader"
            for lbl in sensor_labels:
                expected = scope_pfx + fname + " Mode: "
                if lbl.startswith(expected):
                    mode_val = lbl[len(expected):]
                    if mode_val in ("Leader", "Any", "All"):
                        mode_found = mode_val.lower()
                        break
            mode_for[key] = mode_found

        # Step 3: Start with carried-through entries
        ns_result: dict[str, dict[str, dict[str, dict[str, Any]]]] = {}

        for fname, scopes_map in prev_features_raw.items():
            if not isinstance(scopes_map, dict):
                continue
            for scope_val, sids in scopes_map.items():
                if not isinstance(sids, dict):
                    continue
                for scope_id_val, entry in sids.items():
                    if not isinstance(entry, dict):
                        continue
                    key = f"{fname}||{scope_val}||{scope_id_val}"
                    has_leader = key in triples
                    is_manual = entry.get("triggering_leader", "") == ""
                    if has_leader or is_manual:
                        ns_result.setdefault(fname, {}).setdefault(
                            scope_val, {}
                        )[scope_id_val] = entry

        # Step 4: Handle state_changed path
        is_state_changed = (
            evtype == "state_changed"
            and changed_eid
            and changed_eid in all_leader_entities
        )
        if is_state_changed:
            new_state = self.hass.states.get(changed_eid)
            cv_raw = self._get_current_value(changed_eid, new_state)
            is_skip = self._should_skip_event(cv_raw)

            if not is_skip:
                ts = self._get_timestamp(new_state)
                prev_cv = self._leaders.get(changed_eid, {}).get(
                    "current_value", ""
                )

                for key, leaders_list in triples.items():
                    if changed_eid not in leaders_list:
                        continue

                    parts = key.split("||")
                    fname = parts[0]
                    scope_val = parts[1]
                    scope_id_val = parts[2]
                    scope_pfx = (
                        "Area "
                        if scope_val == "area"
                        else ("Floor " if scope_val == "floor" else "")
                    )
                    mode = mode_for.get(key, "leader")

                    # Evaluate the changed leader
                    this_truth = self._evaluate_leader(
                        changed_eid, fname, scope_pfx, cv_raw, prev_cv
                    )

                    if mode == "leader":
                        new_enabled = this_truth
                    else:
                        values = []
                        for other_eid in leaders_list:
                            if other_eid == changed_eid:
                                values.append(this_truth)
                            else:
                                other_st = self.hass.states.get(other_eid)
                                other_cv = (
                                    other_st.state if other_st else ""
                                )
                                other_prev = self._leaders.get(
                                    other_eid, {}
                                ).get("previous_value", "")
                                other_truth = self._evaluate_leader(
                                    other_eid,
                                    fname,
                                    scope_pfx,
                                    other_cv,
                                    other_prev,
                                )
                                values.append(other_truth)

                        if mode == "all":
                            new_enabled = min(values)
                        else:  # any
                            new_enabled = max(values)

                    # Get previous entry
                    existing_f = ns_result.get(fname, {})
                    existing_s = (
                        existing_f.get(scope_val, {})
                        if isinstance(existing_f, dict)
                        else {}
                    )
                    prev_entry = (
                        existing_s.get(scope_id_val, {})
                        if isinstance(existing_s, dict)
                        else {}
                    )
                    prev_enabled = prev_entry.get("enabled", None)
                    prev_ts = prev_entry.get(
                        "last_changed_timestamp", ts
                    )

                    # Check if enabled flipped
                    leader_dom = changed_eid.split(".")[0]
                    is_button_leader = leader_dom in ["event", "button"]
                    flipped = (
                        prev_enabled is None
                        or prev_enabled != new_enabled
                        or is_button_leader
                    )
                    new_ts = ts if flipped else prev_ts

                    new_entry = {
                        "enabled": new_enabled,
                        "mode": mode,
                        "last_changed_timestamp": new_ts,
                        "triggering_leader": changed_eid,
                    }

                    ns_result.setdefault(fname, {}).setdefault(
                        scope_val, {}
                    )[scope_id_val] = new_entry

        self._features = ns_result

    def _evaluate_leader(
        self,
        entity_id: str,
        feature_name: str,
        scope_prefix: str,
        cv: str,
        prev_cv: str,
    ) -> bool:
        """Evaluate whether a leader enables a feature.

        Matches the Jinja2 `eval_leader` macro exactly.
        Returns the post-Invert boolean enabled value.
        """
        entity_labels = self._get_entity_labels(entity_id)
        dom = entity_id.split(".")[0]

        inc_lbl = (
            scope_prefix + feature_name + " Increasing: True"
        ) in entity_labels
        dec_lbl = (
            scope_prefix + feature_name + " Decreasing: True"
        ) in entity_labels

        if inc_lbl or dec_lbl:
            cur_n = None
            prev_n = None
            try:
                cur_n = float(cv) if cv else None
            except (ValueError, TypeError):
                pass
            try:
                prev_n = float(prev_cv) if prev_cv else None
            except (ValueError, TypeError):
                pass

            has_mov = cur_n is not None and prev_n is not None
            is_inc = has_mov and cur_n > prev_n
            is_dec = has_mov and cur_n < prev_n

            base = (inc_lbl and is_inc) or (dec_lbl and is_dec)
        else:
            # Look for Enable: / Disable: labels
            en_lbl = ""
            dis_lbl = ""
            enable_prefix = scope_prefix + feature_name + " Enable: "
            disable_prefix = scope_prefix + feature_name + " Disable: "
            for lbl in entity_labels:
                if lbl.startswith(enable_prefix):
                    en_lbl = lbl[len(enable_prefix):]
                elif lbl.startswith(disable_prefix):
                    dis_lbl = lbl[len(disable_prefix):]

            if en_lbl or dis_lbl:
                cur_st = self.hass.states.get(entity_id)
                state_val = cur_st.state if cur_st else ""
                by_en = en_lbl != "" and state_val == en_lbl
                by_dis = dis_lbl != "" and state_val == dis_lbl

                if en_lbl and dis_lbl:
                    base = by_en and not by_dis
                elif en_lbl:
                    base = by_en
                else:
                    base = not by_dis
            else:
                # Default truth function
                if dom in ["event", "button"]:
                    base = True
                else:
                    st = self.hass.states.get(entity_id)
                    state_val = st.state if st else ""
                    base = (
                        state_val == feature_name
                        or state_val.lower() in TRUTHY_VALUES
                    )

        # Apply Invert
        inverted = (
            scope_prefix + feature_name + " Invert: True"
        ) in entity_labels
        return (not base) if inverted else base

