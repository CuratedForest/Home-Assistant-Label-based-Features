ERROR_MODE_SCHEMA = vol.Schema(
    {
        vol.Required("error_mode"): vol.In(SUPPORTED_ERROR_MODES),
        vol.Required("message"): cv.string,
        vol.Optional("source", default="Labeled Features"): cv.string,
        vol.Optional("severity", default="medium"): vol.In(["low", "medium", "high"]),
    }
)

# Map for service response selectors (for translation)
ERROR_MODE_SELECTOR = SelectSelector(
    SelectSelectorConfig(
        options=SUPPORTED_ERROR_MODES,
        mode=SelectSelectorMode.DROPDOWN,
        translation_key="error_mode",
    )
)


async def async_setup_services(hass: HomeAssistant) -> None:
    """Set up the services for the labeled_features integration."""
    hass.services.async_register(
        DOMAIN,
        "error_mode",
        _async_handle_error_mode_service,
        schema=ERROR_MODE_SCHEMA,
    )


async def _async_handle_error_mode_service(call: ServiceCall) -> ServiceResponse:
    """Handle the error_mode service call.

    Replicates script.labeled_feature_error_mode behavior.
    """
    error_mode: str = call.data["error_mode"]
    message: str = call.data["message"]
    source: str = call.data["source"]
    severity: str = call.data["severity"]

    if error_mode == "silent":
        # No-op
        pass
    elif error_mode == "log":
        # Write warning to system log
        await hass.services.async_call(
            "system_log",
            "write",
            {
                "level": "warning",
                "message": f"{source}: {message}",
            },
            blocking=True,
        )
    elif error_mode == "alert":
        # Send alert via script.send_alert
        await hass.services.async_call(
            "script",
            "send_alert",
            {
                "alert_severity": severity,
                "alert_title": source,
                "alert_message": message,
            },
            blocking=True,
        )
    elif error_mode == "stop":
        # Log at error level; caller must handle the actual stop
        await hass.services.async_call(
            "system_log",
            "write",
            {
                "level": "error",
                "message": f"{source}: {message}",
            },
            blocking=True,
        )

    return None
