class TestDefaultTruth:
    def test_state_equals_feature_name(self):
        # `input_select` on state 'Night' with `Leader: Night` label
        assert (
            eval_leader_truth(
                labels=[],
                domain="input_select",
                current_value="Night",
                previous_value="Day",
                feature="Night",
                scope="global",
            )
            is True
        )

    def test_state_equals_feature_name_is_case_sensitive(self):
        assert (
            eval_leader_truth(
                labels=[],
                domain="input_select",
                current_value="night",
                previous_value="Day",
                feature="Night",
                scope="global",
            )
            is False
        )

