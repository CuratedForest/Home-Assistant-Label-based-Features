class TestFoldTriple:
    def test_leader_mode_uses_first(self):
        assert fold_triple("leader", [True]) is True
        assert fold_triple("leader", [False]) is False
        # More than one value: leader still uses index 0.
        assert fold_triple("leader", [True, False]) is True

    def test_any_mode(self):
        assert fold_triple("any", [False, True, False]) is True
        assert fold_triple("any", [False, False]) is False

    def test_all_mode(self):
        assert fold_triple("all", [True, True]) is True
        assert fold_triple("all", [True, False]) is False

    def test_empty(self):
        assert fold_triple("any", []) is False
        assert fold_triple("all", []) is False


class TestResolveMode:
    def test_default_leader(self):
        assert resolve_mode([], "Night", "area") == "leader"

    def test_area_mode_label(self):
        assert (
            resolve_mode(["Area Night Mode: All"], "Night", "area") == "all"
        )

    def test_wrong_scope_ignored(self):
        # Floor-prefixed Mode label is ignored for an area-scoped query.
        assert (
            resolve_mode(["Floor Night Mode: All"], "Night", "area") == "leader"
        )

    def test_global_mode(self):
        assert resolve_mode(["Night Mode: Any"], "Night", "global") == "any"
