class TestEnableDisable:
    def test_enable_match(self):
        assert (
            eval_leader_truth(
                labels=["Area Media Playing Enable: playing"],
                domain="media_player",
                current_value="playing",
                previous_value="idle",
                feature="Media Playing",
                scope="area",
            )
            is True
        )

    def test_enable_no_match(self):
        assert (
            eval_leader_truth(
                labels=["Area Media Playing Enable: playing"],
                domain="media_player",
                current_value="paused",
                previous_value="playing",
                feature="Media Playing",
                scope="area",
            )
            is False
        )

    def test_disable_only(self):
        # Only Disable: enabled == NOT (state matches disable value)
        assert (
            eval_leader_truth(
                labels=["Area Screen Disable: standby"],
                domain="media_player",
                current_value="on",
                previous_value="standby",
                feature="Screen",
                scope="area",
            )
            is True
        )
        assert (
            eval_leader_truth(
                labels=["Area Screen Disable: standby"],
                domain="media_player",
                current_value="standby",
                previous_value="on",
                feature="Screen",
                scope="area",
            )
            is False
        )


