class TestModifierMatchers:
    def test_match_enable(self):
        assert match_enable("Area Night Enable: playing", "Night", "Area ") == "playing"

    def test_match_enable_wrong_prefix(self):
        assert match_enable("Floor Night Enable: playing", "Night", "Area ") is None

    def test_match_disable(self):
        assert match_disable("Screen Disable: off", "Screen", "") == "off"

    def test_has_invert(self):
        assert has_invert(["Area Night Invert: True"], "Night", "Area ") is True
        # Case-sensitive True
        assert has_invert(["Area Night Invert: true"], "Night", "Area ") is False

    def test_has_increasing_decreasing(self):
        assert has_increasing(["Screen Increasing: True"], "Screen", "") is True
        assert has_decreasing(["Screen Decreasing: True"], "Screen", "") is True
        assert has_increasing([], "Screen", "") is False


