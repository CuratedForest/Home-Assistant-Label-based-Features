class TestParseLeader:
    def test_bare_leader_is_global(self):
        assert parse_leader_label("Leader: Night") == ("global", "Night")

    def test_area_leader(self):
        assert parse_leader_label("Area Leader: Screen") == ("area", "Screen")

    def test_floor_leader(self):
        assert parse_leader_label("Floor Leader: Night") == ("floor", "Night")

    def test_case_sensitive_keyword(self):
        assert parse_leader_label("leader: Night") is None
        assert parse_leader_label("Area leader: Night") is None

    def test_case_sensitive_feature(self):
        # Lowercase feature is accepted verbatim as the feature name.
        assert parse_leader_label("Leader: night") == ("global", "night")

    def test_non_leader_label(self):
        assert parse_leader_label("Feature Leader") is None
        assert parse_leader_label("Area Follower: Night") is None

    def test_empty_feature_rejected(self):
        assert parse_leader_label("Leader: ") is None


class TestParseProvides:
    def test_bare_provides_is_none_scope(self):
        assert parse_provides_label("Provides: Audio Mode") == ("none", "Audio Mode")

    def test_area_provides(self):
        assert parse_provides_label("Area Provides: Media Player") == (
            "area",
            "Media Player",
        )

    def test_floor_provides(self):
        assert parse_provides_label("Floor Provides: Night") == ("floor", "Night")

    @pytest.mark.parametrize(
        "kw",
        ["Component", "Min", "Max", "Step", "Unit", "Icon", "Initial", "Mode", "Device Class"],
    )
    def test_modifier_labels_filtered(self, kw):
        assert parse_provides_label(f"Area Provides: Audio Mode {kw}: foo") is None

    def test_provides_option_not_a_provides(self):
        # "Provides Option: <F>" doesn't match "Provides: <F>" — different pattern.
        assert parse_provides_label("Area Provides Option: Audio Mode") is None


class TestParseMode:
    def test_bare_mode_is_global(self):
        assert parse_mode_label("Night Mode: All") == ("global", "Night", "all")

    def test_area_mode(self):
        assert parse_mode_label("Area Screen Mode: Leader") == ("area", "Screen", "leader")

    def test_floor_mode(self):
        assert parse_mode_label("Floor Night Mode: Any") == ("floor", "Night", "any")

    def test_case_sensitive_values(self):
        # `Mode:` value is case-sensitive on the label side (Leader|Any|All);
        # anything else fails to parse.
        assert parse_mode_label("Night Mode: leader") is None
        assert parse_mode_label("Night Mode: ALL") is None


